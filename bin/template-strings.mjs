/**
 * Writes the texts of the bundled trade templates to includes/template-strings.php,
 * as a table of English texts and their translation calls. The plugin reads
 * the table to translate the templates, and `wp i18n make-pot` finds the
 * texts in it.
 *
 * Run `npm run i18n:templates` after changing a template.
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join( dirname( fileURLToPath( import.meta.url ) ), '..' );
const strings = new Map();

function add( text, template ) {
	if ( 'string' === typeof text && '' !== text ) {
		if ( ! strings.has( text ) ) {
			strings.set( text, new Set() );
		}
		strings.get( text ).add( template );
	}
}

for ( const file of readdirSync( join( root, 'templates' ) )
	.filter( ( name ) => name.endsWith( '.json' ) )
	.sort() ) {
	const data = JSON.parse(
		readFileSync( join( root, 'templates', file ), 'utf8' )
	);

	add( data.title, file );
	add( data.description, file );
	add( data.keywords, file );
	Object.values( data.messages || {} ).forEach( ( text ) =>
		add( text, file )
	);

	for ( const step of data.steps ) {
		add( step.title, file );
		add( step.description, file );

		for ( const field of step.fields ) {
			[ 'label', 'help', 'placeholder', 'unit' ].forEach( ( key ) =>
				add( field[ key ], file )
			);
			( field.options || [] ).forEach( ( option ) => {
				add( option.label, file );
				add( option.help, file );
			} );
		}
	}
}

// PHP string literal: single quotes, or double quotes when the text has line breaks.
function literal( text ) {
	if ( text.includes( '\n' ) ) {
		return (
			'"' +
			text.replace( /[\\"$]/g, '\\$&' ).replace( /\n/g, '\\n' ) +
			'"'
		);
	}

	return "'" + text.replace( /[\\']/g, '\\$&' ) + "'";
}

const lines = [ ...strings ].map( ( [ text, files ] ) => {
	const comment = /\{[a-z_]+\}/.test( text )
		? '\t\t/* translators: Keep the words in braces, such as {name}, as they are. */\n'
		: '';

	return `\t\t// From ${ [ ...files ].join( ', ' ) }.\n\t\t${ literal(
		text
	) } =>\n${ comment.replace( /^\t\t/, '\t\t\t' ) }\t\t\t__( ${ literal(
		text
	) }, 'primiko' ),`;
} );

writeFileSync(
	join( root, 'includes', 'template-strings.php' ),
	`<?php
/**
 * Texts of the bundled trade templates and their translations.
 *
 * Generated by bin/template-strings.mjs from the files in templates/. Do not
 * edit by hand. Read by Templates::translate().
 *
 * @package Primiko
 */

defined( 'ABSPATH' ) || exit;

/**
 * Returns the translation of each text of the templates, keyed by the text
 * in English.
 *
 * @return array<string, string>
 */
function primiko_template_strings() {
	return array(
${ lines.join( '\n' ) }
	);
}
`
);

// eslint-disable-next-line no-console
console.log(
	`${ strings.size } texts written to includes/template-strings.php`
);
